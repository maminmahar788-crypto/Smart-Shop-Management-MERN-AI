require('dotenv').config();
const express = require('express');
const cors = require('cors');
const connectDB = require('./config/db');
const app = express();
app.use(cors({ origin: process.env.CLIENT_URL || 'http://localhost:5173' }));
app.use(express.json({ limit: '1mb' }));
app.get('/api/health', (req,res)=>res.json({ status:'ok', service:'smart-shop-management-api' }));
app.use('/api/auth', require('./routes/auth.routes'));
app.use('/api/products', require('./routes/product.routes'));
app.use('/api/inventory', require('./routes/inventory.routes'));
app.use('/api/sales', require('./routes/sales.routes'));
app.use('/api/expenses', require('./routes/expense.routes'));
app.use('/api/reports', require('./routes/reports.routes'));
app.use('/api/ai', require('./routes/ai.routes'));
app.use((req,res)=>res.status(404).json({ message:'API route not found.' }));
app.use((err,req,res,next)=>{ console.error(err); res.status(err.status || 500).json({ message: err.status ? err.message : 'Server error. Check server terminal for details.' }); });
const port = Number(process.env.PORT || 5000);
connectDB().then(()=>app.listen(port,()=>console.log(`API running at http://localhost:${port}`))).catch(err=>{ console.error('Could not connect to MongoDB:',err.message); process.exit(1); });
